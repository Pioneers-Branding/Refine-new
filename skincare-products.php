                    currentSubcat = this.getAttribute('data-subcat');
                    subBtns.forEach(sb => {
                        sb.classList.remove('bg-brand', 'text-white');
                        sb.classList.add('bg-brand/5', 'text-brand-muted');
                    });
                    this.classList.add('bg-brand', 'text-white');
                    this.classList.remove('bg-brand/5', 'text-brand-muted');

                    updateDisplay();
                });
            });
