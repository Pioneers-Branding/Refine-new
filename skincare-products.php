            const items = document.querySelectorAll('.product-item');

            let currentBrand = 'all';
            let currentSubcat = 'all';

            function updateDisplay() {
                items.forEach(item => {
                    const itemBrand = item.getAttribute('data-category');
                    const itemSubcat = item.getAttribute('data-subcat');

                    let show = false;
                    if (currentBrand === 'all') {
                        show = true;
                    } else if (currentBrand === itemBrand) {
                        if (currentBrand === 'fixderma') {
                            if (currentSubcat === 'all' || itemSubcat === currentSubcat || itemSubcat === 'all') {
                                show = true;
                            }
                        } else {
                            show = true;
                        }
                    }

                    item.style.display = show ? 'flex' : 'none';
                });
            }

            filterBtns.forEach(btn => {
                btn.addEventListener('click', function() {
                    currentBrand = this.getAttribute('data-brand');
                    currentSubcat = 'all';

                    filterBtns.forEach(b => {
                        b.classList.remove('active', 'bg-brand', 'text-white', 'shadow-md');
                        b.classList.add('bg-[#faf9f6]', 'text-brand-deeper');
                    });
                    this.classList.add('active', 'bg-brand', 'text-white', 'shadow-md');
                    this.classList.remove('bg-[#faf9f6]', 'text-brand-deeper');

                    if (currentBrand === 'fixderma') {
                        subNav.classList.remove('hidden');
                        subBtns.forEach(sb => {
                            sb.classList.remove('bg-brand', 'text-white');
                            sb.classList.add('bg-brand/5', 'text-brand-muted');
                        });
                        subBtns[0].classList.add('bg-brand', 'text-white');
                        subBtns[0].classList.remove('bg-brand/5', 'text-brand-muted');
                    } else {
                        subNav.classList.add('hidden');
                    }

                    updateDisplay();
                });
            });

