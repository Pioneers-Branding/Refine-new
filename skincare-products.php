            const filterBtns = document.querySelectorAll('.brand-filter-btn');
            const items = document.querySelectorAll('.product-item');

            filterBtns.forEach(btn => {
                btn.addEventListener('click', function() {
                    const brand = this.getAttribute('data-brand');

                    filterBtns.forEach(b => {
                        b.classList.remove('active', 'bg-brand', 'text-white', 'shadow-md');
                        b.classList.add('bg-[#faf9f6]', 'text-brand-deeper');
                    });
                    this.classList.add('active', 'bg-brand', 'text-white', 'shadow-md');
                    this.classList.remove('bg-[#faf9f6]', 'text-brand-deeper');

                    items.forEach(item => {
                        const itemCat = item.getAttribute('data-category');
                        if (brand === 'all' || itemCat === brand) {
                            item.style.display = 'flex';
                        } else {
                            item.style.display = 'none';
                        }
                    });
                });
            });
        });
    </script>

