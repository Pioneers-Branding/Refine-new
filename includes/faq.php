<!-- Vanilla JS for FAQ Accordion -->
<script>
document.addEventListener('DOMContentLoaded', () => {
    const faqItems = document.querySelectorAll('.faq-home-item');
    faqItems.forEach(item => {
        item.addEventListener('click', () => {
            const isActive = item.classList.contains('active');
            
            // Close other items
            faqItems.forEach(el => {
                el.classList.remove('active');
                const content = el.querySelector('.faq-home-content');
                if (content) content.style.height = '0px';
            });

            // Toggle clicked item
            if (!isActive) {
                item.classList.add('active');
                const content = item.querySelector('.faq-home-content');
                if (content) {
                    content.style.height = content.scrollHeight + 'px';
                }
            }
        });
    });
});
</script>

