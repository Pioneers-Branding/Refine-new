        tabBtns.forEach(btn => {
            btn.addEventListener('click', function() {
                const targetId = this.getAttribute('data-target');

                // Update tab buttons
                tabBtns.forEach(b => {
                    b.classList.remove('active', 'text-[#1e60d5]', 'font-semibold');
                    b.classList.add('text-slate-500', 'font-medium');
                    const ind = b.querySelector('.tab-indicator');
                    if (ind) {
                        ind.classList.remove('bg-[#1e60d5]');
                        ind.classList.add('bg-transparent');
                    }
                });

                this.classList.add('active', 'text-[#1e60d5]', 'font-semibold');
                this.classList.remove('text-slate-500', 'font-medium');
                const activeInd = this.querySelector('.tab-indicator');
                if (activeInd) {
                    activeInd.classList.add('bg-[#1e60d5]');
                    activeInd.classList.remove('bg-transparent');
                }

                // Switch panels
                tabPanels.forEach(panel => {
                    if (panel.id === targetId) {
                        panel.classList.remove('hidden');
                        panel.classList.add('block');
                    } else {
                        panel.classList.add('hidden');
                        panel.classList.remove('block');
                    }
                });
            });
        });
    });
